import { NavLink, Outlet, useNavigate } from 'react-router-dom';
import { useAuth } from '../../../auth-module/frontend/components/AuthContext';
import './Layout.css';

const navItems = [
  { to: 'disaster-events', label: 'Disaster Events', icon: CalendarIcon },
  { to: 'volunteers', label: 'Volunteers', icon: UsersIcon },
  { to: 'resources', label: 'Resources', icon: PackageIcon },
  { to: 'tasks', label: 'Tasks', icon: ClipboardIcon },
];

export default function Layout() {
  const { user, logout } = useAuth();
  const navigate = useNavigate();

  function handleLogout() {
    logout();
    navigate('/login');
  }

  return (
    <div className="layout">
      <aside className="sidebar">
        <div className="sidebar-header">
          <div className="logo">RN</div>
          <div>
            <div className="app-name">RescueNet</div>
            <div className="role-label">Relief Organization</div>
          </div>
        </div>

        <nav className="sidebar-nav">
          <span className="nav-label">NAVIGATION</span>
          {navItems.map(({ to, label, icon: Icon }) => (
            <NavLink
              key={to}
              to={to}
              className={({ isActive }) => `nav-item${isActive ? ' active' : ''}`}
            >
              <Icon />
              <span>{label}</span>
            </NavLink>
          ))}
        </nav>

        <div className="sidebar-footer">
          <div className="org-name">{user?.profile?.name || 'Organization'}</div>
          <div className="org-user">{user?.username || ''}</div>
          <button className="logout-btn" onClick={handleLogout}>
            <LogoutIcon />
            <span>Sign out</span>
          </button>
        </div>
      </aside>

      <main className="main-content">
        <Outlet />
      </main>
    </div>
  );
}

